#!/usr/bin/env bash
# koompi-displays saves a rule per display, keeps the rules of displays that are away, names a mirror's source the same way, and writes the same file twice
set -uo pipefail

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
SCRIPT="$REPO_ROOT/dots/.local/bin/koompi-displays"

failed=0
case_failed=0
fail() { printf 'FAIL: %s\n' "$1" >&2; failed=1; case_failed=1; }
end_case() { (( case_failed )) || printf 'PASS %s\n' "$1"; case_failed=0; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
stub="$tmp/bin"
mkdir -p "$stub" "$tmp/config/hypr" "$tmp/run"
chmod 700 "$tmp/run"
for cmd in bash jq mktemp mv rm sleep cat mkdir setsid; do
    path="$(command -v "$cmd")" || { echo "FAIL: test host has no $cmd" >&2; exit 1; }
    ln -s "$path" "$stub/$cmd"
done
cp "$REPO_ROOT/tests/displays-hyprctl" "$stub/hyprctl"
chmod +x "$stub/hyprctl"

lua="$tmp/config/hypr/monitors.lua"
fresh() {
    cp "$REPO_ROOT/tests/displays-monitors.json" "$tmp/state.json"
    : > "$tmp/eval.log"
    rm -rf "$lua" "$tmp/run/koompi-displays"
}
monitors() { jq "$1" "$tmp/state.json" > "$tmp/state.new" && mv "$tmp/state.new" "$tmp/state.json"; }
run_displays() {
    env -i PATH="$stub" HOME="$tmp" XDG_CONFIG_HOME="$tmp/config" XDG_RUNTIME_DIR="$tmp/run" \
        HYPRCTL_STATE="$tmp/state.json" HYPRCTL_EVAL_LOG="$tmp/eval.log" bash "$SCRIPT" "$@" > "$tmp/out" 2>&1
}
persist() {
    run_displays rate "$1" "${2:-74.97}" || fail "rate $1 ${2:-74.97} failed: $(cat "$tmp/out")"
    run_displays keep || fail "keep failed: $(cat "$tmp/out")"
}
keys() { grep -o 'output = ".*"' "$lua" | sed 's/^output = //' | tr '\n' ' '; }
body() { tail -n +3 "$lua"; }
rule() {
    printf 'hl.monitor({\n    output = "%s",\n    mode = "%s",\n    position = "%s",\n    scale = %s' "$1" "$2" "$3" "$4"
    [[ -z ${5:-} ]] || printf ',\n    transform = %s' "$5"
    [[ -z ${6:-} ]] || printf ',\n    mirror = "%s"' "$6"
    printf '\n})'
}

fresh
persist HDMI-A-1
want="$(rule 'desc:BOE 0x0CE0' 1920x1200@60 0x0 1 0)
$(rule 'desc:WAM HDMI 18250023' 1920x1080@74.97 1920x0 1.25 0)"
[[ "$(body)" == "$want" ]] || fail "the layout is not one desc: rule per display: $(cat "$lua")"
first="$(cat "$lua")"
persist HDMI-A-1
[[ "$(cat "$lua")" == "$first" ]] || fail "saving the same monitors twice wrote a different file: $(cat "$lua")"
end_case "a rule per display, and the same monitors give the same file"

fresh
printf -- '-- Generated by koompi-displays on 2026-10-01 10:00:00. Do not edit manually.\n\n%s\n%s\n%s\n%s\n' \
    "$(rule eDP-1 1920x1200@60 0x0 1)" "$(rule HDMI-A-1 1920x1080@60 1920x0 1)" \
    "$(rule DP-9 1024x768@60 0x0 1)" "$(rule 'desc:Dell Inc. U2720Q ABC123' 3840x2160@60 3840x0 1.5)" > "$lua"
persist HDMI-A-1
want="$(rule DP-9 1024x768@60 0x0 1)
$(rule 'desc:Dell Inc. U2720Q ABC123' 3840x2160@60 3840x0 1.5)
$(rule 'desc:BOE 0x0CE0' 1920x1200@60 0x0 1 0)
$(rule 'desc:WAM HDMI 18250023' 1920x1080@74.97 1920x0 1.25 0)"
[[ "$(body)" == "$want" ]] || fail "old port rules of connected monitors stayed, or rules of unplugged ones went: $(cat "$lua")"
first="$(cat "$lua")"
persist HDMI-A-1
[[ "$(cat "$lua")" == "$first" ]] || fail "a second save with the same monitors changed the file: $(cat "$lua")"
end_case "a port rule is replaced once its port is seen, rules of absent displays stay"

fresh
monitors '.[0].availableModes += ["1920x1200@48.00Hz"]'
persist HDMI-A-1
cp "$tmp/state.json" "$tmp/both.json"
jq '[.[0]]' "$tmp/both.json" > "$tmp/state.json"
persist eDP-1 48
[[ "$(keys)" == '"desc:WAM HDMI 18250023" "desc:BOE 0x0CE0" ' ]] || fail "unplugging the HDMI display lost its rule or doubled eDP's: $(keys)"
grep -qF 'mode = "1920x1200@48",' "$lua" || fail "the eDP rule did not take the new rate: $(cat "$lua")"
jq '.[1].name = "DP-2" | .[1].x = 3000' "$tmp/both.json" > "$tmp/state.json"
persist DP-2
[[ "$(keys)" == '"desc:BOE 0x0CE0" "desc:WAM HDMI 18250023" ' ]] || fail "the display on a new port did not replace its own rule: $(keys)"
grep -qF 'position = "3000x0",' "$lua" || fail "the display kept its old place after moving to another port: $(cat "$lua")"
grep -q 'output = "DP-2"' "$lua" && fail "a port name was saved for a display that has a description"
end_case "unplugged and plugged into another port: still one rule for the display"

fresh
monitors '.[1].description = "ACME \"Pro\" \\ 27" | .[1].transform = 1'
luac_path="$(command -v luac || true)"
[[ -z "$luac_path" ]] || ln -s "$luac_path" "$stub/luac"
persist HDMI-A-1
rm -f "$stub/luac"
want="$(rule 'desc:ACME \"Pro\" \\ 27' 1920x1080@74.97 1920x0 1.25 1)"
[[ "$(body | tail -n 7)" == "$want" ]] || fail "a quote and a backslash in a description are not escaped, or the rotation is not carried: $(cat "$lua")"
[[ -z "$luac_path" ]] || "$luac_path" -p "$lua" || fail "the file with a quote and a backslash in a description is not valid lua"
end_case "a quote and a backslash in a description are escaped, a rotation is carried"

fresh
monitors '.[0].description = .[1].description'
persist HDMI-A-1
[[ "$(keys)" == '"eDP-1" "HDMI-A-1" ' ]] || fail "two displays with one description were both saved by it: $(keys)"
fresh
monitors '.[0].description = ""'
persist HDMI-A-1
[[ "$(keys)" == '"eDP-1" "desc:WAM HDMI 18250023" ' ]] || fail "a display with no description was not saved by its port: $(keys)"
fresh
monitors '.[1].description = "WAM\u0007HDMI"'
persist HDMI-A-1
[[ "$(keys)" == '"desc:BOE 0x0CE0" "HDMI-A-1" ' ]] || fail "a description with a control character was written into the file: $(keys)"
fresh
monitors '.[0].description = "WAM HDMI"'
persist HDMI-A-1
[[ "$(keys)" == '"eDP-1" "desc:WAM HDMI 18250023" ' ]] || fail "a description that starts another one was saved by itself, so its rule would match both displays: $(keys)"
end_case "a description that is empty, shared, unprintable or the start of another keeps the port"

fresh
monitors '.[1].mirrorOf = "0"'
printf -- '-- old\n\n%s\n%s\n' "$(rule HDMI-A-1 1920x1080@75 1920x0 1 '' eDP-1)" "$(rule DP-9 1024x768@60 0x0 1 '' eDP-1)" > "$lua"
persist eDP-1 60
want="$(rule DP-9 1024x768@60 0x0 1 '' eDP-1)
$(rule 'desc:BOE 0x0CE0' 1920x1200@60 0x0 1 0)
$(rule 'desc:WAM HDMI 18250023' 1920x1080@60 1920x0 1.25 0 'desc:BOE 0x0CE0')"
[[ "$(body)" == "$want" ]] || fail "a mirror the plain monitor list hides was not saved with its source by description, or its old port rule stayed, or an absent mirror lost its line: $(cat "$lua")"
first="$(cat "$lua")"
persist eDP-1 60
[[ "$(cat "$lua")" == "$first" ]] || fail "saving a mirror twice wrote a different file: $(cat "$lua")"
end_case "a mirror is saved with its source by description, and a second save changes nothing"

fresh
monitors '.[1].mirrorOf = "eDP-1"'
persist eDP-1 60
want="$(rule 'desc:BOE 0x0CE0' 1920x1200@60 0x0 1 0)
$(rule 'desc:WAM HDMI 18250023' 1920x1080@60 1920x0 1.25 0 'desc:BOE 0x0CE0')"
[[ "$(body)" == "$want" ]] || fail "a mirrorOf that is a port name was not followed to its source: $(cat "$lua")"
end_case "mirrorOf as the source's name is followed too"

fresh
monitors '.[1].mirrorOf = "0" | .[0].description = .[1].description'
persist eDP-1 60
want="$(rule eDP-1 1920x1200@60 0x0 1 0)
$(rule HDMI-A-1 1920x1080@60 1920x0 1.25 0 eDP-1)"
[[ "$(body)" == "$want" ]] || fail "a source whose description is shared was not named by its port: $(cat "$lua")"
end_case "a source with a shared description is named by its port"

fresh
monitors '.[1].mirrorOf = "7"'
persist eDP-1 60
want="$(rule 'desc:BOE 0x0CE0' 1920x1200@60 0x0 1 0)
$(rule 'desc:WAM HDMI 18250023' 1920x1080@60 1920x0 1.25 0)"
[[ "$(body)" == "$want" ]] || fail "a mirror of a monitor that is not listed was saved with a made-up source: $(cat "$lua")"
end_case "a mirror whose source is not listed is saved without a mirror line"

fresh
monitors '.[1].disabled = true'
printf -- '-- old\n\n%s\n' "$(rule 'desc:WAM HDMI 18250023' 1920x1080@60 1920x0 1.25 0)" > "$lua"
persist eDP-1 60
want="$(rule 'desc:WAM HDMI 18250023' 1920x1080@60 1920x0 1.25 0)
$(rule 'desc:BOE 0x0CE0' 1920x1200@60 0x0 1 0)"
[[ "$(body)" == "$want" ]] || fail "a disabled monitor was saved as an enabled one, or lost its old rule: $(cat "$lua")"
fresh
monitors '.[1].disabled = true'
persist eDP-1 60
[[ "$(keys)" == '"desc:BOE 0x0CE0" ' ]] || fail "a disabled monitor with no old rule got one: $(keys)"
end_case "a disabled monitor keeps its old rule and gets none otherwise"

(( failed )) && exit 1
echo "ok   displays desc: rules follow the display, absent displays keep theirs, mirrors follow their source, the same monitors write the same file"
